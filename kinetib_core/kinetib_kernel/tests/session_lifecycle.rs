//! PostgreSQL-backed session tests. Set KINETIB_TEST_DATABASE_URL to a
//! disposable database; without it these integration tests return early.

use bcrypt::hash;
use kinetib_app::auth::{authenticate_password, AuthenticatedPrincipal};
use kinetib_db::DbContext;
use kinetib_kernel::sessions::{SessionLookupError, SessionStore};
use sqlx::postgres::PgPoolOptions;
use std::env;
use std::sync::Arc;
use std::time::Duration;

async fn test_principal() -> Option<(DbContext, AuthenticatedPrincipal)> {
    let url = match env::var("KINETIB_TEST_DATABASE_URL") {
        Ok(url) if !url.trim().is_empty() => url,
        _ => {
            eprintln!("skipping session integration test: KINETIB_TEST_DATABASE_URL is unset");
            return None;
        }
    };

    let pool = PgPoolOptions::new()
        .max_connections(1)
        .connect(&url)
        .await
        .expect("connect disposable test database");
    sqlx::raw_sql(
        r#"CREATE TEMP TABLE users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            email TEXT NOT NULL UNIQUE,
            password TEXT NOT NULL,
            auth_provider TEXT NOT NULL
        ) ON COMMIT PRESERVE ROWS"#,
    )
    .execute(&pool)
    .await
    .expect("create temporary users table");

    let password_hash = hash("session-test-password", 4).expect("create low-cost test hash");
    let email = "session-test@example.test";
    let _inserted = sqlx::query!(
        "INSERT INTO users (email, password, auth_provider) VALUES ($1, $2, 'local') RETURNING id",
        email,
        password_hash
    )
    .fetch_one(&pool)
    .await
    .expect("insert temporary test user");

    let db = DbContext { pool };
    let principal = authenticate_password(&db, email, "session-test-password")
        .await
        .expect("authenticate temporary user");
    Some((db, principal))
}

#[tokio::test]
async fn sessions_authenticate_revoke_and_expire() {
    let Some((_db, principal)) = test_principal().await else {
        return;
    };
    let store = SessionStore::new(4, Duration::from_millis(250)).expect("create session store");

    let token = store.issue(principal.clone()).await.expect("issue session");
    assert_eq!(token.len(), 64);
    assert_eq!(
        store.authenticate(&token).await.unwrap().user_id(),
        principal.user_id()
    );

    assert!(store.revoke(&token).await);
    assert_eq!(
        store.authenticate(&token).await,
        Err(SessionLookupError::InvalidOrExpired)
    );
    assert!(!store.revoke(&token).await);

    let expiring = store
        .issue(principal)
        .await
        .expect("issue expiring session");
    tokio::time::sleep(Duration::from_millis(300)).await;
    assert_eq!(
        store.authenticate(&expiring).await,
        Err(SessionLookupError::InvalidOrExpired)
    );
}

#[tokio::test]
async fn concurrent_session_reads_return_the_bound_principal() {
    let Some((_db, principal)) = test_principal().await else {
        return;
    };
    let store = Arc::new(SessionStore::new(8, Duration::from_secs(60)).expect("create store"));
    let expected_user_id = principal.user_id();
    let token = store.issue(principal).await.expect("issue session");

    let mut tasks = Vec::with_capacity(16);
    for _ in 0..16 {
        let store = Arc::clone(&store);
        let token = token.clone();
        tasks.push(tokio::spawn(async move {
            store
                .authenticate(&token)
                .await
                .expect("session remains valid")
                .user_id()
        }));
    }
    for task in tasks {
        assert_eq!(task.await.expect("join session reader"), expected_user_id);
    }
}

#[tokio::test]
async fn session_count_is_bounded() {
    let Some((_db, principal)) = test_principal().await else {
        return;
    };
    let store = SessionStore::new(1, Duration::from_secs(60)).expect("create one-session store");
    let _first = store.issue(principal.clone()).await.expect("first session");
    let second = store.issue(principal).await;
    assert!(matches!(
        second,
        Err(kinetib_kernel::sessions::SessionStoreError::AtCapacity)
    ));
    assert_eq!(store.len().await, 1);
}
