use kinetib_db::DbContext;
use sqlx::postgres::PgPoolOptions;
use std::env;

/// Creates a single-connection test context with temporary PostgreSQL tables.
///
/// Set `KINETIB_TEST_DATABASE_URL` to a disposable database whose normal
/// schema/migrations (including `public.recurring_frequency`) are installed.
/// SQLx's `query!` macros are checked against that normal schema at build time;
/// at runtime, these connection-local temporary tables shadow the real tables.
///
/// `raw_sql` is used only for the multi-statement temporary-table DDL. All
/// application data statements below use compile-time checked `query!` macros.
pub async fn test_db() -> Option<DbContext> {
    let database_url = match env::var("KINETIB_TEST_DATABASE_URL") {
        Ok(url) if !url.trim().is_empty() => url,
        _ => {
            eprintln!("skipping PostgreSQL integration test: KINETIB_TEST_DATABASE_URL is unset");
            return None;
        }
    };

    let pool = PgPoolOptions::new()
        .max_connections(1)
        .connect(&database_url)
        .await
        .expect("connect to KINETIB_TEST_DATABASE_URL");

    sqlx::raw_sql(
        r#"
        CREATE TEMP TABLE users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            email TEXT NOT NULL UNIQUE,
            password TEXT NOT NULL,
            auth_provider TEXT NOT NULL
        ) ON COMMIT PRESERVE ROWS;

        CREATE TEMP TABLE transactions (
            id BIGINT PRIMARY KEY,
            user_id BIGINT NOT NULL,
            name TEXT NOT NULL,
            price DOUBLE PRECISION NOT NULL,
            description TEXT NOT NULL,
            datetime BIGINT NOT NULL,
            category TEXT NOT NULL,
            is_recurring BOOLEAN NOT NULL,
            recurring_frequency public.recurring_frequency NULL,
            receipt_url TEXT NULL
        ) ON COMMIT PRESERVE ROWS;
        "#,
    )
    .execute(&pool)
    .await
    .expect("create temporary test tables");

    Some(DbContext { pool })
}

pub async fn insert_user(db: &DbContext, email: &str, password_hash: &str) -> i64 {
    let row = sqlx::query!(
        "INSERT INTO users (email, password, auth_provider) VALUES ($1, $2, 'local') RETURNING id",
        email,
        password_hash
    )
    .fetch_one(&db.pool)
    .await
    .expect("insert temporary test user");

    row.id
}
