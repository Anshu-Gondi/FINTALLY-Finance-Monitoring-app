float MatrixMatcher::compute_match_score(const uint16_t candidate[16], const uint16_t target[16]) {
    int matching_bits = 0;
    for (int i = 0; i < 16; ++i) {
        uint16_t match = ~(candidate[i] ^ target[i]);
        for (int b = 0; b < 16; ++b) {
            if ((match >> b) & 1) matching_bits++;
        }
    }
    return static_cast<float>(matching_bits) / 256.0f;
}

char MatrixMatcher::match_glyph(const std::vector<uint8_t>& cropped_patch, int patch_w, int patch_h) {
    if (patch_w == 0 || patch_h == 0) return '?';

    uint16_t candidate_grid[16] = {0};

    float scale_w = 16.0f / static_cast<float>(patch_w);
    float scale_h = 16.0f / static_cast<float>(patch_h);

    for (int r = 0; r < 16; ++r) {
        int src_y = static_cast<int>(r / scale_h);
        src_y = std::min(std::max(src_y, 0), patch_h - 1);

        for (int c = 0; c < 16; ++c) {
            int src_x = static_cast<int>(c / scale_w);
            src_x = std::min(std::max(src_x, 0), patch_w - 1);

            uint8_t pixel = cropped_patch[src_y * patch_w + src_x];
            // Adaptive thresholding fallback: check against local intensity mean if pixel range varies
            if (pixel > 100) {
                candidate_grid[r] |= (1 << (15 - c));
            }
        }
    }

    char best_char = '?';
    float max_score = 0.45f; // Lowered baseline acceptance threshold slightly to capture low-contrast chart text

    for (const auto& tpl : templates_) {
        float score = compute_match_score(candidate_grid, tpl.grid);
        if (score > max_score) {
            max_score = score;
            best_char = tpl.character;
        }
    }

    return best_char;
}

static std::vector<BoundingBox> extract_components(
    const uint8_t* image, int width, int height,
    int min_y, int max_y, int channels
) {
    (void)height;

    std::vector<BoundingBox> boxes;
    std::vector<uint8_t> visited(width * (max_y - min_y), 0);

    for (int y = min_y; y < max_y; ++y) {
        for (int x = 0; x < width; ++x) {
            int local_y = y - min_y;
            int v_idx = local_y * width + x;
            int img_idx = (y * width + x) * channels;
            uint8_t val = (channels == 3) ? image[img_idx + 1] : image[img_idx];

            if (val > 100 && !visited[v_idx]) {
                BoundingBox box{x, y, x, y};
                std::queue<std::pair<int, int>> q;

                q.push({x, y});
                visited[v_idx] = 1;

                while (!q.empty()) {
                    auto [cx, cy] = q.front();
                    q.pop();

                    box.min_x = std::min(box.min_x, cx);
                    box.max_x = std::max(box.max_x, cx);
                    box.min_y = std::min(box.min_y, cy);
                    box.max_y = std::max(box.max_y, cy);

                    static const int dx[] = {-1, 1, 0, 0};
                    static const int dy[] = {0, 0, -1, 1};

                    for (int d = 0; d < 4; ++d) {
                        int nx = cx + dx[d];
                        int ny = cy + dy[d];

                        if (nx >= 0 && nx < width && ny >= min_y && ny < max_y) {
                            int n_local_y = ny - min_y;
                            int n_v_idx = n_local_y * width + nx;
                            int n_img_idx = (ny * width + nx) * channels;
                            uint8_t n_val = (channels == 3) ? image[n_img_idx + 1] : image[n_img_idx];

                            if (n_val > 100 && !visited[n_v_idx]) {
                                visited[n_v_idx] = 1;
                                q.push({nx, ny});
                            }
                        }
                    }
                }

                if (box.width() >= 1 && box.height() >= 2 && box.area() >= 2) {
                    boxes.push_back(box);
                }
            }
        }
    }

    std::sort(boxes.begin(), boxes.end(), [](const BoundingBox& a, const BoundingBox& b) {
        return a.min_x < b.min_x;
    });

    return boxes;
}

std::string MatrixMatcher::recognize_line(
    const uint8_t* image, int img_width,
    int line_y_start, int line_y_end, int channels
) {
    std::string recognized_text;

    std::vector<BoundingBox> char_boxes = extract_components(
        image, img_width, line_y_end - line_y_start, line_y_start, line_y_end, channels
    );

    int last_max_x = -1;

    for (const auto& box : char_boxes) {
        if (last_max_x != -1 && (box.min_x - last_max_x) > 8) {
            recognized_text += " ";
        }

        int patch_w = box.width();
        int patch_h = box.height();

        std::vector<uint8_t> patch(patch_w * patch_h);
        for (int py = 0; py < patch_h; ++py) {
            for (int px = 0; px < patch_w; ++px) {
                int img_x = box.min_x + px;
                int img_y = box.min_y + py;
                int idx = (img_y * img_width + img_x) * channels;
                patch[py * patch_w + px] = (channels == 3) ? image[idx + 1] : image[idx];
            }
        }

        char c = match_glyph(patch, patch_w, patch_h);
        if (c != '?') {
            recognized_text += c;
        }

        last_max_x = box.max_x;
    }

    return recognized_text;
}

std::string MatrixMatcher::recognize_chart_labels(const uint8_t* hsv_buffer, int width, int height) {
    std::stringstream chart_ss;
    chart_ss << "[CHART_TEXT_DATA]\n";

    // Multi-scale overlapping band scanning to capture both dense numbers and larger axis labels
    int band_heights[] = {16, 24, 32};
    int line_count = 0;

    std::map<int, std::string> detected_lines;

    for (int bh : band_heights) {
        int stride = bh / 2;
        for (int y = 0; y <= height - bh; y += stride) {
            std::string line_text = recognize_line(hsv_buffer, width, y, y + bh, 3);
            if (!line_text.empty() && line_text.find_first_not_of(" ") != std::string::npos) {
                // Deduplicate or aggregate overlapping band captures
                bool redundant = false;
                for (auto const& [existing_y, text] : detected_lines) {
                    if (std::abs(existing_y - y) < bh && text == line_text) {
                        redundant = true;
                        break;
                    }
                }
                if (!redundant) {
                    detected_lines[y] = line_text;
                }
            }
        }
    }

    for (auto const& [y_pos, text] : detected_lines) {
        line_count++;
        chart_ss << "  - Line " << line_count << " [Y:" << y_pos << "-" << (y_pos + 24) << "]: " << text << "\n";
    }

    if (line_count == 0) {
        chart_ss << "  - No structured glyphs matched on chart axes.\n";
    }

    return chart_ss.str();
}

